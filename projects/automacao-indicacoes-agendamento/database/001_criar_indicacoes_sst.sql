CREATE TABLE IF NOT EXISTS `IndicacoesSST` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `id_parceiro` VARCHAR(100) NOT NULL COMMENT 'Identificador completo, por exemplo 22_D',
  `id_parceiro_base` VARCHAR(100) NOT NULL COMMENT 'Identificador sem a sigla do banco, por exemplo 22',
  `sigla_banco` CHAR(1) NOT NULL COMMENT 'Identificador D ou Q da operação',
  `nome_parceiro` VARCHAR(255) NOT NULL,
  `operacao` VARCHAR(50) NOT NULL,
  `consultora` VARCHAR(255) NOT NULL,
  `nome_cliente` VARCHAR(255) NOT NULL,
  `cnpj_cliente` VARCHAR(14) NULL,
  `nome_contato` VARCHAR(255) NOT NULL,
  `telefone_contato` VARCHAR(20) NOT NULL,
  `email_contato` VARCHAR(255) NULL,
  `quantidade_funcionarios` VARCHAR(50) NULL,
  `cargos` TEXT NULL,
  `observacao` TEXT NULL,
  `empresa_rd_id` VARCHAR(64) NULL,
  `contato_rd_id` VARCHAR(64) NULL,
  `negociacao_rd_id` VARCHAR(64) NULL,
  `status_integracao` VARCHAR(30) NOT NULL DEFAULT 'recebida',
  `mensagem_integracao` TEXT NULL,
  `data_hora_indicacao` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `data_hora_atualizacao` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_indicacoes_sst_negociacao_rd` (`negociacao_rd_id`),
  KEY `idx_indicacoes_sst_parceiro` (`id_parceiro`),
  KEY `idx_indicacoes_sst_operacao` (`operacao`),
  KEY `idx_indicacoes_sst_data_hora` (`data_hora_indicacao`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
